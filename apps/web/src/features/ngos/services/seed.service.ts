/**
 * Seeds the synthetic Delhi NGO directory into the active repository if empty.
 */
export async function seedDemoNGOs(repo: INGORepository): Promise<number> {
  let seeded = 0;
  for (const ngo of SYNTHETIC_DELHI_NGOS) {
    const existing = await repo.findById(ngo.ngo_id);
    if (!existing) {
      await repo.create(ngo);
      seeded++;
    }
  }

  if (seeded > 0) {
    logger.info(`Seeded ${seeded} synthetic demo NGOs into repository`, "NGO_SEED");
  }
  return seeded;
}

